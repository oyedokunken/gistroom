// Generates labeled-free placeholder PNGs at the final ratios, plus the manifest, PROMPTS.md
// and content/alt.ts (Section 17.5, step 5). Real art replaces these and flips status to DRAFT or APPROVED.
// Usage: node scripts/graphics/placeholders.mjs [--force]  (never overwrites art that is not PLACEHOLDER)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { Resvg } from "@resvg/resvg-js";
import { ASSETS, SIZES, STYLE_LOCK } from "./assets.mjs";

const root = process.cwd();
const imgDir = path.join(root, "apps", "web", "public", "images");
const manifestPath = path.join(root, "design", "assets.manifest.json");
mkdirSync(imgDir, { recursive: true });

const old = existsSync(manifestPath)
  ? JSON.parse(readFileSync(manifestPath, "utf8"))
  : { assets: [] };
const prev = new Map((old.assets ?? []).map((a) => [a.id, a]));

// Adire style repeat in the palette: a diamond and dot tile on pale green.
function placeholderSvg(w, h, transparent) {
  const tile = 80;
  const bg = transparent ? "" : `<rect width="${w}" height="${h}" fill="#E4F4EB"/>`;
  const pattern = `<defs><pattern id="p" width="${tile}" height="${tile}" patternUnits="userSpaceOnUse">
    <path d="M40 8 L72 40 L40 72 L8 40 Z" fill="none" stroke="#0E7A43" stroke-width="3" opacity="${transparent ? 0.35 : 0.55}"/>
    <circle cx="40" cy="40" r="6" fill="#FFC20E" opacity="${transparent ? 0.6 : 0.9}"/>
  </pattern></defs>`;
  const frame = transparent
    ? `<rect x="${w * 0.1}" y="${h * 0.1}" width="${w * 0.8}" height="${h * 0.8}" rx="32" fill="url(#p)"/>`
    : `<rect width="${w}" height="${h}" fill="url(#p)"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">${pattern}${bg}${frame}</svg>`;
}

const entries = [];
for (const a of ASSETS) {
  const spec = SIZES[a.kind];
  const [mw, mh] = spec.master;
  const existing = prev.get(a.id);
  const keep = existing && existing.status !== "PLACEHOLDER";
  const sizes = spec.widths.map((width) => ({
    width,
    height: Math.round((width * mh) / mw),
    file: `${a.id}-${width}.png`,
  }));
  if (!keep) {
    // Placeholders only need the smallest variant on disk to keep the repo light; larger ones are listed
    // in the manifest as planned sizes once real art exists.
    const s = sizes[0];
    const png = new Resvg(placeholderSvg(s.width, s.height, Boolean(a.transparent)))
      .render()
      .asPng();
    writeFileSync(path.join(imgDir, s.file), png);
  }
  entries.push(
    keep
      ? existing
      : {
          id: a.id,
          placement: a.placement,
          master: null,
          sizes: [sizes[0]],
          plannedSizes: sizes.map((s) => s.width),
          alt: a.alt,
          decorative: Boolean(a.decorative) || a.alt === "",
          prompt: a.prompt,
          status: "PLACEHOLDER",
          createdAt: existing?.createdAt ?? new Date().toISOString(),
        },
  );
}
writeFileSync(manifestPath, `${JSON.stringify({ version: 1, assets: entries }, null, 2)}\n`);

// PROMPTS.md
const lines = [
  "# Image prompts",
  "",
  "Paste the style lock first, then the asset prompt. Save masters in `design/masters/` (the optimizer script arrives with the first real art).",
  "Never let an image generator draw letters. Text is composed in code with Graphik (CLAUDE.md Section 17.4).",
  "",
  "## Style lock",
  "",
  STYLE_LOCK,
  "",
  "## Canvas sizes",
  "",
  "| Kind | Master | Shipped widths |",
  "|---|---|---|",
  ...Object.entries(SIZES).map(
    ([k, v]) => `| ${k} | ${v.master.join(" by ")} | ${v.widths.join(", ")} |`,
  ),
  "",
  "## Assets",
  "",
  ...ASSETS.flatMap((a) => [
    `### ${a.id}`,
    "",
    `Placement: ${a.placement}. Kind: ${a.kind}${a.transparent ? ", transparent background" : ""}.`,
    "",
    a.prompt,
    "",
  ]),
];
writeFileSync(path.join(root, "design", "PROMPTS.md"), `${lines.join("\n")}\n`);

// content/alt.ts (generated, strings stay out of components per R10)
const altEntries = ASSETS.map((a) => `  "${a.id}": ${JSON.stringify(a.alt)},`).join("\n");
writeFileSync(
  path.join(root, "apps", "web", "src", "content", "alt.ts"),
  `// Generated by scripts/graphics/placeholders.mjs from scripts/graphics/assets.mjs. Edit there.\nexport const alt: Record<string, string> = {\n${altEntries}\n};\n`,
);
// lib/art.generated.ts: id to shipped file, alt and size, read by getArt()
const artMap = Object.fromEntries(
  entries.map((e) => {
    const size = e.sizes[0];
    return [
      e.id,
      {
        src: `/images/${size.file}`,
        alt: e.decorative ? "" : e.alt,
        width: size.width,
        height: size.height,
      },
    ];
  }),
);
writeFileSync(
  path.join(root, "apps", "web", "src", "lib", "art.generated.ts"),
  `// Generated by scripts/graphics/placeholders.mjs. Edit scripts/graphics/assets.mjs instead.\nexport const artMap: Record<string, { src: string; alt: string; width: number; height: number }> = ${JSON.stringify(artMap, null, 2)};\n`,
);
console.log(
  `graphics: ${entries.length} assets, ${entries.filter((e) => e.status === "PLACEHOLDER").length} placeholders`,
);
